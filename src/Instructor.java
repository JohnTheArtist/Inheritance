


public class Instructor extends Person{
    int student_num;

    String classname;
    Instructor(int student_num, String classname, int age, String name, double height, double weight, String color){
        this.student_num = student_num;
        this.classname = classname;
        this.age = age;
        this.name = name;
        this.height = height;
        this.weight = weight;
        this.color = color;


    }
}
